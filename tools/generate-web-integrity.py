"""Generate compiled trust data after reviewing Web assets; --check never updates it."""
from pathlib import Path
import hashlib,sys
root=Path(__file__).resolve().parents[1]
web=root/'Testplan/Web'
files=sorted(p for p in web.rglob('*') if p.is_file())
lines=['// Generated by tools/generate-web-integrity.py; review assets before regenerating.',
       'namespace Testplan { internal static class WebIntegrityData {',
       'internal static readonly string[] Entries = new string[] {']
for p in files:
 name=p.relative_to(web).as_posix()
 if any(c in name for c in ['"','\\','|']):raise ValueError(name)
 lines.append('"'+hashlib.sha256(p.read_bytes()).hexdigest()+'|'+name+'",')
lines+=['}; } }','']
expected='\n'.join(lines)
target=root/'Testplan/Authorization/WebIntegrityData.cs'
if '--check' in sys.argv:
 assert target.read_text()==expected,'Web assets changed: review and regenerate integrity data before building'
 print('PASS compiled Web integrity hashes match reviewed assets')
else:target.write_text(expected)
